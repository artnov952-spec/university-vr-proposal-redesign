  if (role) return 'Tanlangan rol: ' + translate(role[1], language);
  const grant = value.match(/^Изменено локальное право: (.+), (.+)$/);
  if (grant) return "Mahalliy ruxsat o'zgardi: " + translate(grant[1], language) + ', ' + translate(grant[2], language);
